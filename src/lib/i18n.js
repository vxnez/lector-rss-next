function resolver(idioma, clave) {
  const partes = String(clave).split(".");
  let nodo = DICCIONARIO[idioma];
  for (const p of partes) {
    if (nodo && typeof nodo === "object" && p in nodo) nodo = nodo[p];
    else {
      nodo = undefined;
      break;
    }
  }
  if (typeof nodo === "string") return nodo;
  if (idioma !== "es") return resolver("es", clave);
  return clave;
}

function aplicarVars(texto, vars) {
  if (!vars || typeof texto !== "string") return texto;
  return texto.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
}


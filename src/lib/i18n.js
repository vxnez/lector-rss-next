function resolverEn(textos, clave) {
  const partes = String(clave).split(".");
  let nodo = textos;
  for (const p of partes) {
    if (nodo && typeof nodo === "object" && p in nodo) nodo = nodo[p];
    else {
      nodo = undefined;
      break;
    }
  }
  if (typeof nodo === "string") return nodo;
  return undefined;
}

// Resuelve en el idioma activo con fallback al español si falta la clave.
function resolver(clave, idioma) {
  const dict = idioma === "en" ? TEXTOS_EN : TEXTOS_ES;
  return resolverEn(dict, clave) ?? resolverEn(TEXTOS_ES, clave) ?? clave;
}

function aplicarVars(texto, vars) {
  if (!vars || typeof texto !== "string") return texto;
  return texto.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
}

const IdiomaContexto = createContext({
  t: (clave) => String(clave),
  locale: "es-ES",
  idioma: "es",
  setIdioma: () => {},
});

const LOCALES = { es: "es-ES", en: "en-US" };

function idiomaInicial() {
  try {
    const guardado = window.localStorage.getItem(CLAVE_IDIOMA);
    if (IDIOMAS_VALIDOS.includes(guardado)) return guardado;
  } catch {
    // Sin almacenamiento: español por defecto.
  }
  return "es";
}

export function IdiomaProvider({ children }) {
  const [idioma, setIdiomaEstado] = useState(idiomaInicial);

  useEffect(() => {
    try {
      document.documentElement.lang = idioma === "en" ? "en" : "es";
    } catch {
      // Sin DOM disponible: se omite.
    }
  }, [idioma]);

  const setIdioma = useCallback((valor) => {
    const normalizado = IDIOMAS_VALIDOS.includes(valor) ? valor : "es";
    try {
      window.localStorage.setItem(CLAVE_IDIOMA, normalizado);
    } catch {
      // Sin almacenamiento: solo cambia en esta vista.
    }
    setIdiomaEstado(normalizado);
  }, []);

  const t = useCallback((clave, vars) => aplicarVars(resolver(clave, idioma), vars), [idioma]);

  return (
    <IdiomaContexto.Provider value={{ t, locale: LOCALES[idioma] || LOCALES.es, idioma, setIdioma }}>
      {children}
    </IdiomaContexto.Provider>
  );
}

export function useIdioma() {
  return useContext(IdiomaContexto);
}

function resolver(clave) {
  const partes = String(clave).split(".");
  let nodo = TEXTOS;
  for (const p of partes) {
    if (nodo && typeof nodo === "object" && p in nodo) nodo = nodo[p];
    else {
      nodo = undefined;
      break;
    }
  }
  if (typeof nodo === "string") return nodo;
  return clave;
}

function aplicarVars(texto, vars) {
  if (!vars || typeof texto !== "string") return texto;
  return texto.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
}

const IdiomaContexto = createContext({
  t: (clave) => String(clave),
  locale: "es-ES",
});

const LOCALE = "es-ES";

export function IdiomaProvider({ children }) {
  useEffect(() => {
    try {
      document.documentElement.lang = "es";
    } catch {
      // Sin DOM disponible: se omite.
    }
  }, []);

  const t = useCallback((clave, vars) => aplicarVars(resolver(clave), vars), []);

  return (
    <IdiomaContexto.Provider value={{ t, locale: LOCALE }}>
      {children}
    </IdiomaContexto.Provider>
  );
}

export function useIdioma() {
  return useContext(IdiomaContexto);
}
